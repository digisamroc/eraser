// AddToManual appends a broker to the manual file's add list, keeping the
// file's comments. The entry is validated as the build would validate it.
func AddToManual(path string, b broker.Broker) error {
	return editManual(path, "add", []any{b})
}

// ExcludeInManual appends exclusions to the manual file's exclude list.
func ExcludeInManual(path string, xs []Exclusion) error {
	items := make([]any, len(xs))
	for i, x := range xs {
		items[i] = x
	}
	return editManual(path, "exclude", items)
}

// editManual appends items to one top-level list, validates the whole
// result, and only then writes it.
func editManual(path, key string, items []any) error {
	data, err := os.ReadFile(path) //nolint:gosec // G304: path is the repo's manual file
	if err != nil {
		return fmt.Errorf("failed to read %s: %w", path, err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return fmt.Errorf("failed to parse %s: %w", path, err)
	}
	if len(doc.Content) == 0 || doc.Content[0].Kind != yaml.MappingNode {
		return fmt.Errorf("%s: expected a mapping with add/overrides/exclude", path)
	}
	root := doc.Content[0]

	var seq *yaml.Node
	for i := 0; i+1 < len(root.Content); i += 2 {
		if root.Content[i].Value == key {
			seq = root.Content[i+1]
		}
	}
	if seq == nil {
		seq = &yaml.Node{Kind: yaml.SequenceNode, Tag: "!!seq"}
		root.Content = append(root.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: key}, seq)
	}
	seq.Style = 0 // "add: []" becomes a block list
	for _, item := range items {
		var n yaml.Node
		if err := n.Encode(item); err != nil {
			return fmt.Errorf("failed to encode %s entry: %w", key, err)
		}
		seq.Content = append(seq.Content, &n)
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return fmt.Errorf("failed to write %s: %w", path, err)
	}
	if err := enc.Close(); err != nil {
		return fmt.Errorf("failed to write %s: %w", path, err)
	}

	var m Manual
	dec := yaml.NewDecoder(bytes.NewReader(buf.Bytes()))
	dec.KnownFields(true)
	if err := dec.Decode(&m); err != nil && !errors.Is(err, io.EOF) {
		return fmt.Errorf("edited %s does not parse: %w", path, err)
	}
	if err := m.validate(); err != nil {
		return err
	}
	return writeFileAtomic(path, buf.Bytes())
}

// WriteDatabase writes the broker database with the generated-file header,
// sorted by name, replacing path atomically.
func WriteDatabase(path string, db *broker.BrokerDatabase) error {
	sort.SliceStable(db.Brokers, func(i, j int) bool {
		return strings.ToLower(db.Brokers[i].Name) < strings.ToLower(db.Brokers[j].Name)
	})
	out, err := yaml.Marshal(db)
	if err != nil {
		return fmt.Errorf("failed to serialize brokers: %w", err)
	}
	header := "# GENERATED by cmd/registry-import from " + RegistryURL + "\n" +
		"# Do not edit by hand. Change data/brokers.manual.yaml and regenerate:\n" +
		"#   go run ./cmd/registry-import\n"
	return writeFileAtomic(path, append([]byte(header), out...))
}

// writeFileAtomic replaces path with data via a temp file and rename. The
// broker files are public data checked into the repository.
func writeFileAtomic(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".brokers-*.yaml")
	if err != nil {
		return fmt.Errorf("failed to write %s: %w", path, err)
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // no-op once renamed
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("failed to write %s: %w", path, err)
	}
	if err := tmp.Chmod(0o644); err != nil {
		_ = tmp.Close()
		return fmt.Errorf("failed to write %s: %w", path, err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("failed to write %s: %w", path, err)
	}
	return os.Rename(tmp.Name(), path)
}
